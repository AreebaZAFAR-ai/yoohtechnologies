import type { Metadata } from "next";
import { site } from "./site";

/**
 * Shared SEO helpers: page metadata and JSON-LD builders.
 *
 * Every page builds its <head> through `pageMetadata()` so titles, canonicals, Open Graph
 * and Twitter tags stay complete and consistent. (Next.js replaces — not merges — a parent's
 * `openGraph` object when a page sets its own, so partial objects silently drop tags.)
 */

/** Stable entity IDs so every page references the same Organization / WebSite node. */
export const ORG_ID = `${site.url}/#organization`;
export const WEBSITE_ID = `${site.url}/#website`;

/** Generated by app/opengraph-image.tsx. */
export const DEFAULT_OG_IMAGE = "/opengraph-image";

/** Absolute canonical URL for a site path ("/" → origin with trailing slash). */
export const absoluteUrl = (path = "/") => (path === "/" ? `${site.url}/` : `${site.url}${path}`);

type PageSeo = {
  /** Page title. Gets " | YOOH Technologies" appended unless `absoluteTitle` is set. */
  title: string;
  description: string;
  /** Canonical path, e.g. "/services/website-development". */
  path: string;
  /** Use `title` as-is (already contains the brand). */
  absoluteTitle?: boolean;
  type?: "website" | "article";
  publishedTime?: string;
  modifiedTime?: string;
  noindex?: boolean;
  /** OG/Twitter image path; defaults to the site-wide card. */
  image?: string;
};

export function pageMetadata({
  title,
  description,
  path,
  absoluteTitle = false,
  type = "website",
  publishedTime,
  modifiedTime,
  noindex = false,
  image = DEFAULT_OG_IMAGE,
}: PageSeo): Metadata {
  const fullTitle = absoluteTitle ? title : `${title} | ${site.name}`;
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    ...(noindex ? { robots: { index: false, follow: true } } : {}),
    openGraph: {
      type,
      siteName: site.name,
      locale: "en_US",
      url: path,
      title: fullTitle,
      description,
      ...(type === "article" ? { publishedTime, modifiedTime, authors: [site.name] } : {}),
      images: [{ url: image, width: 1200, height: 630, alt: fullTitle }],
    },
    twitter: { card: "summary_large_image", title: fullTitle, description, images: [image] },
  };
}

/* ------------------------------------------------------------------
   JSON-LD builders
   ------------------------------------------------------------------ */

type Thing = Record<string, unknown>;

export function organizationSchema(knowsAbout: string[]): Thing {
  const { email, phone } = site.contact;
  const sameAs = site.socials.map((s) => s.href).filter(Boolean);
  return {
    "@type": "Organization",
    "@id": ORG_ID,
    name: site.name,
    alternateName: site.shortName,
    url: absoluteUrl("/"),
    logo: {
      "@type": "ImageObject",
      "@id": `${site.url}/#logo`,
      url: `${site.url}/logo.png`,
      width: 512,
      height: 512,
      caption: site.name,
    },
    image: { "@id": `${site.url}/#logo` },
    slogan: site.tagline,
    description: site.description,
    knowsAbout,
    address: { "@type": "PostalAddress", addressCountry: site.contact.country },
    email: site.contact.email || undefined,
    areaServed: site.areaServed.map((name) => ({ "@type": "Country", name })),
    ...(sameAs.length ? { sameAs } : {}),
    ...(email || phone
      ? {
          contactPoint: {
            "@type": "ContactPoint",
            contactType: "sales",
            availableLanguage: ["English"],
            ...(email ? { email } : {}),
            ...(phone ? { telephone: phone } : {}),
          },
        }
      : {}),
  };
}

export function websiteSchema(): Thing {
  return {
    "@type": "WebSite",
    "@id": WEBSITE_ID,
    url: absoluteUrl("/"),
    name: site.name,
    alternateName: site.shortName,
    description: site.description,
    publisher: { "@id": ORG_ID },
    inLanguage: "en",
  };
}

/** WebPage-family node for a single page (WebPage, AboutPage, ContactPage, CollectionPage…). */
export function webPageSchema({
  type = "WebPage",
  path,
  name,
  description,
  breadcrumb = false,
}: {
  type?: string;
  path: string;
  name: string;
  description: string;
  breadcrumb?: boolean;
}): Thing {
  const url = absoluteUrl(path);
  return {
    "@type": type,
    "@id": `${url}#webpage`,
    url,
    name,
    description,
    isPartOf: { "@id": WEBSITE_ID },
    about: { "@id": ORG_ID },
    inLanguage: "en",
    ...(breadcrumb ? { breadcrumb: { "@id": `${url}#breadcrumb` } } : {}),
  };
}

export type Crumb = { name: string; path: string };

export function breadcrumbSchema(crumbs: Crumb[]): Thing {
  const last = crumbs[crumbs.length - 1];
  return {
    "@type": "BreadcrumbList",
    "@id": `${absoluteUrl(last.path)}#breadcrumb`,
    itemListElement: crumbs.map((c, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: c.name,
      item: absoluteUrl(c.path),
    })),
  };
}

export function faqSchema(path: string, faqs: { q: string; a: string }[]): Thing {
  return {
    "@type": "FAQPage",
    "@id": `${absoluteUrl(path)}#faq`,
    mainEntity: faqs.map((f) => ({
      "@type": "Question",
      name: f.q,
      acceptedAnswer: { "@type": "Answer", text: f.a },
    })),
  };
}

/** Wrap nodes in a single @graph document. */
export const graph = (...nodes: Thing[]) => ({ "@context": "https://schema.org", "@graph": nodes });
